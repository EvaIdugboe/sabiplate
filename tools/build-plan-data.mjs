// Builds site/assets/plan-data.js from the recipe master (data/) and the authored shop tables (tools/).
import { readFile, writeFile } from 'node:fs/promises';
const json = async (p) => JSON.parse(await readFile(p, 'utf8'));
const foods = await json('data/foods.json');
const rows = await json('data/recipe_ingredients.json');
const recs = await json('data/recipes.json');
const defaultPlan = await json('data/default-plan.json');
const map = await json('tools/shop-map.json');
const items = {};
for (const line of (await readFile('tools/shop-items.txt', 'utf8')).split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const [key, name, cat, pack, unit, price, storage] = line.split('|');
  items[key] = { name, cat, pack: Number(pack), unit, price: Number(price), storage };
}
const ing = {}, problems = [];
for (const r of rows) {
  const g = Number(r.grams);
  if (!r.food_key || !(g > 0)) { problems.push(`bad row ${r.recipe_id} #${r.ingredient_no}`); continue; }
  if (!foods[r.food_key]) problems.push(`no food data: ${r.food_key} (${r.recipe_id})`);
  (ing[r.recipe_id] ??= []).push([r.food_key, Math.round(g * 10) / 10, r.ingredient_text]);
}
const nutrition = {};
for (const r of recs) nutrition[r.id] = [Math.round(Number(r.kcal)), Math.round(Number(r.protein_g) * 10) / 10, Math.round(Number(r.carbs_g) * 10) / 10, Math.round(Number(r.fat_g) * 10) / 10];
for (const k of Object.keys(foods)) {
  if (k === 'seasoning' || k === 'tomato') continue;
  const targets = map[k] || (items[k] ? [[k, 1]] : null);
  if (!targets) problems.push(`no shop item for food: ${k}`);
  else for (const [item] of targets) if (!items[item]) problems.push(`map points at missing item: ${k} -> ${item}`);
}
for (const day of defaultPlan) for (const id of day) if (!ing[id]) problems.push(`default plan recipe missing: ${id}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const out = { version: '20261117-r2', foods, ing, nutrition, defaultPlan, items, map };
await writeFile('site/assets/plan-data.js', '/* Generated by tools/build-plan-data.mjs. Do not edit by hand. */\nwindow.SABI_PLAN_DATA=' + JSON.stringify(out) + ';\n');
console.log('recipes', Object.keys(ing).length, 'ingredient rows', rows.length, 'foods', Object.keys(foods).length, 'items', Object.keys(items).length);
